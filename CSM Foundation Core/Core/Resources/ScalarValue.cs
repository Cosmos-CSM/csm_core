    ///     Double precision floating point number.
    /// </summary>
    DOUBLE,

    /// <summary>
    ///     Integer number.
    /// </summary>
    INT,

    /// <summary>
    ///     String value.
    /// </summary>
    STRING,

    /// <summary>
    ///    Boolean value.
    /// </summary>
    BOOL,

    /// <summary>
    ///     Enumeration value.
    /// </summary>
    ENUM,
}
